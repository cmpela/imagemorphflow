def generate_assay_summary(
    df: pd.DataFrame,
    report_root: str | Path,
    *,
    assay_title: str = "Cell Painting assay summary",
    output_name: str = "summary_assay.html",
    column_map: Mapping[str, str] | None = None,
    profile_features: Iterable[str] | None = None,
    active_cutoff: float = 5.0,
    relative_cell_count_cutoff: float = 50.0,
    embedding_method: str = "umap",
    embedding_n_neighbors: int = 15,
    embedding_min_dist: float = 0.2,
    embedding_metric: str = "cosine",
    moa_colors: Mapping[str, str] | None = None,
    inactive_color: str = "#B8C0C8",
    unknown_moa_color: str = "#8C96A0",
    moas_per_induction_panel: int = 10,
    exclude_controls: bool = True,
    random_state: int = 42,
    overwrite: bool = True,
    safe_filename_function: Callable[[Any], str] | None = None,
) -> pd.DataFrame:
    """Create an assay-wide HTML summary with plots and a report browser.

    The UMAP/PCA is fitted only on active, non-toxic profiles that also pass
    the relative-cell-count cutoff.
    """
    if df.empty:
        raise ValueError("The input dataframe is empty.")
    if moas_per_induction_panel < 1:
        raise ValueError("moas_per_induction_panel must be at least 1.")
    required_fields = {
        "plate", "well_id", "irac_group", "moa", "induction",
        "relative_cell_count",
    }
    columns = {
        field: _resolve_column(
            df,
            field,
            column_map,
            required=field in required_fields,
        )
        for field in COLUMN_ALIASES
    }
    frame = _prepare_profiles(
        df,
        columns,
        active_cutoff=active_cutoff,
        relative_cell_count_cutoff=relative_cell_count_cutoff,
        exclude_controls=exclude_controls,
    )
    if frame.empty:
        raise ValueError("No treatment profiles remain after excluding controls.")

    if profile_features is None:
        features = [
            str(column) for column in df.columns
            if str(column).startswith(("Cells_", "Cytoplasm_", "Nuclei_"))
        ]
    else:
        features = [str(column) for column in profile_features]
    missing_features = sorted(set(features).difference(df.columns))
    if missing_features:
        raise KeyError(f"Profile features were not found: {missing_features[:10]}")
    if not features:
        raise ValueError("No Cell Painting profile features were found.")

    report_root = Path(report_root)
    report_root.mkdir(parents=True, exist_ok=True)
    output_path = report_root / output_name
    if output_path.exists() and not overwrite:
        return pd.DataFrame([{"Assay_Summary_HTML": output_path, "Status": "skipped"}])
    safe_filename = safe_filename_function or _resolve_safe_filename()

    resolved_colors = _color_map(frame["_moa"], moa_colors, unknown_moa_color)
    base_records = []
    for _, row in frame.iterrows():
        report_link, report_available = _relative_report_link(
            output_path,
            report_root,
            row[columns["plate"]],
            row[columns["well_id"]],
            safe_filename,
        )
        source_group = (
            "NISSO" if row["_is_nisso"]
            else ("IRAC" if row["_is_irac"] else "Other")
        )
        plate_well = (
            _text(row[columns["plate_well"]])
            if columns["plate_well"] else ""
        )
        condition = (
            _text(row[columns["condition"]])
            if columns["condition"] else ""
        )
        concentration = (
            _text(row[columns["concentration"]])
            if columns["concentration"] else ""
        )
        record = {
            "record_index": len(base_records),
            "display_name": row["_display_name"],
            "compound_id": (
                _text(row[columns["compound_id"]])
                if columns["compound_id"] else ""
            ),
            "well_id": _text(row[columns["well_id"]]),
            "plate": _text(row[columns["plate"]]),
            "plate_well": plate_well,
            "condition": condition,
            "concentration": concentration,
            "source_group": source_group,
            "moa": row["_moa"],
            "moa_color": resolved_colors.get(row["_moa"], unknown_moa_color),
            "induction": _number(row["_induction"]),
            "relative_cell_count": _number(row["_relative_cell_count"]),
            "active": bool(row["_active"]),
            "toxic": bool(row["_toxic"]),
            "qc_pass": bool(row["_qc_pass"]),
            "report_link": report_link,
            "report_available": report_available,
        }
        record["status_rank"] = (
            2 if record["toxic"] else (0 if record["active"] else 1)
        )
        record["search_text"] = " ".join(
            _text(record[key])
            for key in (
                "display_name", "compound_id", "well_id", "plate",
                "plate_well", "condition", "concentration", "source_group",
                "moa", "induction", "relative_cell_count",
            )
        ).casefold()
        base_records.append(record)

    qc_positions = np.flatnonzero(frame["_qc_pass"].to_numpy())
    embedding_records = []
    embedding_feature_count = 0
    embedding_description = ""
    embedding_empty_message = (
        "At least three active, non-toxic profiles are required for the embedding."
    )
    if len(qc_positions) >= 3:
        qc_numeric = (
            frame.loc[qc_positions, features]
            .apply(pd.to_numeric, errors="coerce")
            .replace([np.inf, -np.inf], np.nan)
        )
        usable_features = [
            column for column in qc_numeric.columns
            if qc_numeric[column].notna().any()
            and qc_numeric[column].nunique(dropna=True) > 1
        ]
        embedding_feature_count = len(usable_features)
        if embedding_feature_count >= 2:
            from sklearn.impute import SimpleImputer
            matrix = SimpleImputer(strategy="median").fit_transform(
                qc_numeric[usable_features]
            )
            coordinates, embedding_description = _compute_embedding(
                matrix,
                method=embedding_method,
                random_state=random_state,
                n_neighbors=embedding_n_neighbors,
                min_dist=embedding_min_dist,
                metric=embedding_metric,
            )
            embedding_description += f" · {embedding_feature_count} features"
            for coordinate_position, frame_position in enumerate(qc_positions):
                embedding_records.append({
                    **base_records[int(frame_position)],
                    "x": float(coordinates[coordinate_position, 0]),
                    "y": float(coordinates[coordinate_position, 1]),
                    "color": base_records[int(frame_position)]["moa_color"],
                })
        else:
            embedding_empty_message = (
                "Fewer than two variable profile features remain in the active, "
                "non-toxic subset."
            )

    rng = np.random.default_rng(random_state)
    induction_records = []
    for record in base_records:
        if record["induction"] is None:
            continue
        induction_records.append({
            **record,
            "jitter": float(rng.uniform(-0.28, 0.28)),
            "color": record["moa_color"] if record["active"] else inactive_color,
        })
    moa_order = sorted(
        {record["moa"] for record in induction_records},
        key=str.casefold,
    )
    induction_panels = []
    for start in range(0, len(moa_order), moas_per_induction_panel):
        categories = moa_order[start:start + moas_per_induction_panel]
        category_set = set(categories)
        induction_panels.append({
            "categories": categories,
            "records": [
                record for record in induction_records
                if record["moa"] in category_set
            ],
        })
    induction_values = [
        record["induction"] for record in induction_records
        if record["induction"] is not None
    ]
    if induction_values:
        induction_min = min(0.0, active_cutoff, min(induction_values))
        induction_max = max(active_cutoff, max(induction_values))
        induction_padding = (induction_max - induction_min or 1.0) * 0.06
        induction_y_min = induction_min - induction_padding
        induction_y_max = induction_max + induction_padding
    else:
        induction_y_min = 0.0
        induction_y_max = max(active_cutoff, 1.0)

    stats = [
        {"label": "Treatment profiles", "value": len(frame)},
        {"label": "NISSO profiles", "value": int(frame["_is_nisso"].sum())},
        {"label": "IRAC profiles", "value": int(frame["_is_irac"].sum())},
        {"label": f"Active (> {active_cutoff:g}%)", "value": int(frame["_active"].sum())},
        {"label": "Inactive", "value": int((~frame["_active"]).sum())},
        {"label": "Toxic", "value": int(frame["_toxic"].sum())},
        {"label": "Active + non-toxic", "value": int(frame["_qc_pass"].sum())},
    ]
    axis_prefix = "UMAP" if embedding_method.casefold() == "umap" else "PC"
    payload = {
        "stats": stats,
        "active_cutoff": active_cutoff,
        "relative_cell_count_cutoff": relative_cell_count_cutoff,
        "embedding_records": embedding_records,
        "embedding_description": embedding_description,
        "embedding_empty_message": embedding_empty_message,
        "embedding_axis_x": f"{axis_prefix} 1",
        "embedding_axis_y": f"{axis_prefix} 2",
        "induction_records": induction_records,
        "induction_panels": induction_panels,
        "moa_order": moa_order,
        "moas_per_induction_panel": moas_per_induction_panel,
        "induction_y_min": induction_y_min,
        "induction_y_max": induction_y_max,
        "moa_colors": resolved_colors,
        "report_records": base_records,
    }
    document = (
        HTML_TEMPLATE
        .replace("@@PAGE_TITLE@@", html.escape(assay_title))
        .replace("@@ASSAY_TITLE@@", html.escape(assay_title))
        .replace("@@ACTIVE_CUTOFF@@", f"{active_cutoff:g}")
        .replace("@@CELL_COUNT_CUTOFF@@", f"{relative_cell_count_cutoff:g}")
        .replace("@@MOAS_PER_PANEL@@", str(moas_per_induction_panel))
        .replace("@@DATA_JSON@@", _json_for_script(payload))
    )
    output_path.write_text(document, encoding="utf-8")

    missing_reports = sum(not record["report_available"] for record in base_records)
    if missing_reports:
        warnings.warn(
            f"{missing_reports} detailed report files were not found. "
            "Links were still created.",
            stacklevel=2,
        )
    return pd.DataFrame([{
        "Assay_Summary_HTML": output_path,
        "Treatment_Profiles": len(frame),
        "NISSO_Profiles": int(frame["_is_nisso"].sum()),
        "IRAC_Profiles": int(frame["_is_irac"].sum()),
        "Active_Profiles": int(frame["_active"].sum()),
        "Inactive_Profiles": int((~frame["_active"]).sum()),
        "Toxic_Profiles": int(frame["_toxic"].sum()),
        "Active_Non_Toxic_Profiles": int(frame["_qc_pass"].sum()),
        "Embedding_Features": embedding_feature_count,
        "Detailed_Reports_Available": len(base_records) - missing_reports,
        "Status": "generated",
    }])


