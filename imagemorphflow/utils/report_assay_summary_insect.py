def _is_missing(value: Any) -> bool:
    if value is None:
        return True
    try:
        return bool(pd.isna(value))
    except (TypeError, ValueError):
        return False


def _text(value: Any, default: str = "") -> str:
    if _is_missing(value):
        return default
    return str(value).strip()


def _number(value: Any) -> float | None:
    if _is_missing(value):
        return None
    try:
        result = float(value)
    except (TypeError, ValueError):
        return None
    return result if math.isfinite(result) else None


def _boolean_flag(value: Any) -> bool:
    if isinstance(value, (bool, np.bool_)):
        return bool(value)
    numeric = _number(value)
    if numeric is not None:
        return numeric == 1
    return _text(value).casefold() in {
        "true", "yes", "y", "toxic", "tox", "warning", "warn",
    }


def _default_safe_filename(value: Any) -> str:
    result = re.sub(r"[^A-Za-z0-9._-]+", "_", _text(value, "report"))
    return result.strip("._") or "report"


def _resolve_safe_filename() -> Callable[[Any], str]:
    try:
        from .report_generator import safe_filename
        return safe_filename
    except (ImportError, AttributeError):
        try:
            from report_generator import safe_filename
            return safe_filename
        except (ImportError, AttributeError):
            return _default_safe_filename


def _resolve_column(
    frame: pd.DataFrame,
    logical_name: str,
    column_map: Mapping[str, str] | None,
    *,
    required: bool = False,
) -> str | None:
    requested = (column_map or {}).get(logical_name)
    if requested is not None:
        if requested not in frame.columns:
            raise KeyError(
                f"column_map[{logical_name!r}]={requested!r} was not found."
            )
        return requested

    casefold_map = {str(column).casefold(): str(column) for column in frame.columns}
    for candidate in COLUMN_ALIASES.get(logical_name, ()):
        if candidate in frame.columns:
            return candidate
        match = casefold_map.get(candidate.casefold())
        if match is not None:
            return match
    if required:
        raise KeyError(
            f"No column was resolved for {logical_name!r}. Tried: "
            f"{COLUMN_ALIASES.get(logical_name, ())}."
        )
    return None


def inspect_assay_summary_inputs(
    df: pd.DataFrame,
    *,
    column_map: Mapping[str, str] | None = None,
) -> pd.DataFrame:
    """Show how assay-summary fields resolve against an input dataframe."""
    records = []
    required_fields = {
        "plate", "well_id", "irac_group", "moa", "induction",
        "relative_cell_count",
    }
    for logical_name in COLUMN_ALIASES:
        column = _resolve_column(df, logical_name, column_map)
        records.append({
            "Field": logical_name,
            "Resolved_Column": column,
            "Required": logical_name in required_fields,
            "Status": "found" if column is not None else "missing",
        })
    features = [
        column for column in df.columns
        if str(column).startswith(("Cells_", "Cytoplasm_", "Nuclei_"))
    ]
    records.append({
        "Field": "profile_features",
        "Resolved_Column": f"{len(features)} feature columns",
        "Required": True,
        "Status": "found" if features else "missing",
    })
    return pd.DataFrame(records)


def _is_nisso(value: Any) -> bool:
    numeric = _number(value)
    if numeric is not None:
        return numeric == 0
    return _text(value).casefold() in {"0", "0.0", "nisso"}


def _is_irac(value: Any) -> bool:
    if _is_missing(value) or _text(value) == "":
        return False
    return not _is_nisso(value)


def _color_map(
    labels: Iterable[str],
    requested: Mapping[str, str] | None,
    unknown_color: str,
) -> dict[str, str]:
    requested = requested or {}
    unique = sorted({_text(label, "Unknown") for label in labels}, key=str.casefold)
    result = {}
    color_index = 0
    for label in unique:
        if label.casefold() in {"", "unknown", "nan", "none"}:
            result[label] = requested.get(label, unknown_color)
        else:
            result[label] = requested.get(
                label,
                DEFAULT_COLORS[color_index % len(DEFAULT_COLORS)],
            )
            color_index += 1
    return result


def _compute_embedding(
    matrix: np.ndarray,
    *,
    method: str,
    random_state: int,
    n_neighbors: int,
    min_dist: float,
    metric: str,
) -> tuple[np.ndarray, str]:
    normalized = method.casefold()
    if normalized == "umap":
        try:
            from umap import UMAP
        except ImportError as error:
            raise ImportError(
                "UMAP requires umap-learn. Install it or use "
                "embedding_method='pca'."
            ) from error
        effective_neighbors = min(max(2, int(n_neighbors)), len(matrix) - 1)
        model = UMAP(
            n_components=2,
            n_neighbors=effective_neighbors,
            min_dist=float(min_dist),
            metric=metric,
            random_state=random_state,
        )
        coordinates = model.fit_transform(matrix)
        return coordinates, (
            f"UMAP · n_neighbors={effective_neighbors} · "
            f"min_dist={min_dist:g} · metric={metric}"
        )
    if normalized == "pca":
        from sklearn.decomposition import PCA
        model = PCA(n_components=2, random_state=random_state)
        coordinates = model.fit_transform(matrix)
        variance = model.explained_variance_ratio_ * 100
        return coordinates, f"PCA · PC1 {variance[0]:.1f}% · PC2 {variance[1]:.1f}%"
    raise ValueError("embedding_method must be 'umap' or 'pca'.")


def _json_for_script(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace(
        "</", "<\\/"
    )


def _relative_report_link(
    output_path: Path,
    report_root: Path,
    plate: Any,
    well_id: Any,
    safe_filename: Callable[[Any], str],
) -> tuple[str, bool]:
    report_path = (
        report_root
        / safe_filename(plate)
        / f"{safe_filename(well_id)}.html"
    )
    relative = os.path.relpath(report_path, output_path.parent)
    link = "/".join(quote(part, safe="-_.") for part in Path(relative).parts)
    return link, report_path.is_file()


def _prepare_profiles(
    df: pd.DataFrame,
    columns: Mapping[str, str | None],
    *,
    active_cutoff: float,
    relative_cell_count_cutoff: float,
    exclude_controls: bool,
) -> pd.DataFrame:
    frame = df.copy()
    well_type = columns["well_type"]
    if exclude_controls and well_type is not None:
        is_control = (
            frame[well_type].fillna("").astype(str).str.strip().str.casefold()
            .isin({"control", "negative control", "positive control"})
        )
        frame = frame.loc[~is_control].copy()

    frame["_induction"] = pd.to_numeric(
        frame[columns["induction"]], errors="coerce"
    )
    frame["_relative_cell_count"] = pd.to_numeric(
        frame[columns["relative_cell_count"]], errors="coerce"
    )
    if frame["_relative_cell_count"].notna().sum() == 0:
        raise ValueError(
            f"Column {columns['relative_cell_count']!r} contains no numeric values."
        )
    maximum_cell_count = frame["_relative_cell_count"].max(skipna=True)
    if maximum_cell_count <= 2 and relative_cell_count_cutoff > 2:
        warnings.warn(
            "Relative cell count appears to use a 0-1 scale, but the cutoff is "
            f"{relative_cell_count_cutoff:g}. Use a matching cutoff or convert the "
            "column to percentages.",
            stacklevel=2,
        )

    frame["_active"] = frame["_induction"].gt(active_cutoff)
    frame["_cell_count_pass"] = frame["_relative_cell_count"].gt(
        relative_cell_count_cutoff
    )
    toxic = columns["toxic"]
    if toxic is not None:
        frame["_toxic"] = frame[toxic].map(_boolean_flag)
    else:
        frame["_toxic"] = ~frame["_cell_count_pass"]
    frame["_qc_pass"] = (
        frame["_active"]
        & frame["_cell_count_pass"]
        & ~frame["_toxic"]
    )

    frame["_is_nisso"] = frame[columns["irac_group"]].map(_is_nisso)
    frame["_is_irac"] = frame[columns["irac_group"]].map(_is_irac)
    frame["_moa"] = frame[columns["moa"]].map(lambda value: _text(value, "Unknown"))
    frame["_display_name"] = frame.apply(
        lambda row: (
            _text(row[columns["trivial_name"]])
            if columns["trivial_name"] is not None
            else ""
        ) or (
            _text(row[columns["compound_id"]])
            if columns["compound_id"] is not None
            else ""
        ) or _text(row[columns["well_id"]]),
        axis=1,
    )
    return frame.reset_index(drop=True)


